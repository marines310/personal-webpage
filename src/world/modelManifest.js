/**
 * Model manifest
 * =============================================================
 * Drop .glb files into  public/models/  using the filenames below
 * and they'll automatically replace the built-in shapes.
 *
 * EVERY ENTRY IS OPTIONAL. Missing files just fall back to the
 * procedural geometry, so you can add them one at a time.
 *
 * See MODELS.md for where to download these.
 * =============================================================
 */

// Respects the deploy base path (vite.config.js `base`), so models
// resolve correctly both locally and on GitHub Pages.
// `import.meta.env` is Vite's, and doesn't exist under plain Node - where it
// isn't undefined but MISSING, so reading .BASE_URL off it throws rather than
// returning undefined. Guarded so this module can be imported by the tests:
// without it, anything that transitively reaches here (Game, and so
// Environment) can't be loaded outside a browser at all.
const BASE = (import.meta.env && import.meta.env.BASE_URL) || '/'
const path = (file) => `${BASE}models/${file}`

export const MODEL_MANIFEST = [
  {
    key: 'car',
    url: path('car.glb'),
    // Fitted to a FOOTPRINT, not just a length - CAR_LENGTH and CAR_WIDTH
    // from Vehicle.js, which are also the collider's dimensions.
    //
    // fitLength alone was not enough. This model is 1.3 wide by 2.0 long, a
    // ratio of 0.65 where a real car is nearer 0.42, so scaling uniformly to
    // 3.96 long made it 2.57 wide - wider than the fire engine, and well
    // wider than its own collider. It looked far bigger than the traffic
    // while measuring shorter than all of it.
    //
    // If you change CAR_SCALE or CAR_WIDTH, change these too. They are
    // numbers that have to agree and there is no way for one to find out
    // about the other: the manifest is loaded before any vehicle exists.
    // tests/traffic.mjs section 7 checks they still match.
    fitBox: { length: 4.4, width: 1.9 },
    // If your car model faces the wrong way, set this to Math.PI
    // (180 degrees) rather than changing any driving code.
    rotationY: 0,
    yOffset: -0.77
  },

  // --- Town / city props (cyberpunk districts) ---
  //
  // `role` is what makes these a POOL rather than three named files. Add a
  // `building_d` line below and every town on the map starts using it; there
  // is nowhere else to edit. Before this, the three keys were also written
  // out inside World.js, so a fourth building was in the manifest, in the
  // loader, and still never appeared anywhere.
  { key: 'building_a', url: path('building_a.glb'), fitLength: 6, role: 'building' },
  { key: 'building_b', url: path('building_b.glb'), fitLength: 7, role: 'building' },
  { key: 'building_c', url: path('building_c.glb'), fitLength: 5, role: 'building' },

  // --- Jungle props ---
  //
  // One pool, deliberately: the street trees and the palms draw from the same
  // list today because there are only two models between them. Splitting
  // 'tree' into 'street' and 'palm' is worth doing when there are enough
  // models for the distinction to be visible, and not before - a role with
  // one model in it is a hard-coded name wearing a costume.
  { key: 'tree_a', url: path('tree_a.glb'), fitLength: 3, role: 'tree' },
  { key: 'tree_b', url: path('tree_b.glb'), fitLength: 3.5, role: 'tree' },

  // --- Made rather than downloaded ---
  //
  // Generated by `node tools/makeModels.mjs`, out of the SAME
  // Textures/colormap.png the Kenney models sample - so they match without
  // being copies of anything. Both had working code paths in World.js since
  // the day they were written and had never once run, because the files did
  // not exist.
  //
  // NO `fitLength` ON THE STREET LAMP, which is the line in this file most
  // likely to be "tidied" by someone later. Every other entry is fitted
  // because a downloaded model arrives at whatever scale its author used.
  // This one is built to the dimensions `addStreetlight()`'s built-in shape
  // already uses - a 4.6 pole, the arm reaching x=0.85 - and everything that
  // places a lamp is positioned against those numbers. Fitting it to 1 unit
  // would shrink a street lamp to the size of a bollard and leave the pool of
  // light it casts spread on the grass around its feet.
  { key: 'rock', url: path('rock.glb'), fitLength: 2 },
  { key: 'streetlight', url: path('streetlight.glb') }
]

/**
 * The keys that share a job, derived from the manifest rather than listed
 * again beside it.
 *
 * Computed once at module load and not per call: `addBuilding()` runs for
 * every building on the map, and rebuilding the same short array a few
 * hundred times a load is work for nothing.
 *
 * A missing role is an EMPTY pool, not an error. `pick()` on an empty array
 * gives undefined, `assets.has(undefined)` is false, and the caller falls
 * back to its built-in shape - which is exactly what the whole manifest
 * promises: every model is optional.
 */
const withRole = (role) => MODEL_MANIFEST.filter(m => m.role === role).map(m => m.key)

export const BUILDING_MODELS = withRole('building')
export const TREE_MODELS = withRole('tree')
